package by.bsu.imageproc.ui;

public enum Method {

    ITERATIVE("Глобальный порог — итеративный", Group.THRESHOLD,
            "Начальный порог T — средняя яркость. Пиксели делятся на две группы G1 (> T) и G2 (≤ T), "
                    + "новый порог T = (m1 + m2) / 2, где m1, m2 — средние яркости групп. Повторяется, пока T меняется "
                    + "больше чем на 0,5. Сходится к ближайшей «долине» гистограммы, начиная от среднего, "
                    + "поэтому на гистограммах с тремя пиками может выбрать не ту долину."),
    OTSU("Глобальный порог — метод Оцу", Group.THRESHOLD,
            "Для каждого k = 0…255 по гистограмме считаются доля класса ω(k), среднее μ(k) и межклассовая дисперсия "
                    + "σ²B(k) = (μT·ω(k) − μ(k))² / (ω(k)·(1 − ω(k))). Порог — k с максимальной σ²B. "
                    + "Это глобальный максимум, поэтому Оцу находит наилучшее по этому критерию разбиение на два класса. "
                    + "η = σ²B / σ²G показывает, насколько хорошо классы разделимы (1 — идеально)."),
    ADAPTIVE_MEAN("Адаптивный порог — среднее окна − C", Group.THRESHOLD,
            "Порог свой для каждого пикселя: T(x, y) = m(x, y) − C, где m — средняя яркость в окне (2r+1)×(2r+1). "
                    + "Медленно меняющаяся освещённость входит в m и не мешает. Сумма по окну берётся из интегрального "
                    + "изображения S четырьмя обращениями: S(D) − S(B) − S(C) + S(A), то есть за O(1) на пиксель "
                    + "при любом размере окна."),
    ADAPTIVE_SAUVOLA("Адаптивный порог — Саувола", Group.THRESHOLD,
            "T(x, y) = m·(1 + k·(s / R − 1)), где m и s — среднее и СКО яркости в окне, R = 128. "
                    + "В однородных областях (малое s) порог опускается ниже среднего — фон не превращается в шум. "
                    + "m и s считаются через два интегральных изображения (сумм и сумм квадратов): "
                    + "s² = E[f²] − (E[f])², O(1) на пиксель."),
    MEDIAN("Медианный фильтр", Group.ORDER,
            "Значения пикселей в окне упорядочиваются по возрастанию, результат — средний элемент (медиана). "
                    + "Импульс 0 или 255 оказывается в конце упорядоченного ряда и в результат не попадает, а ступенька "
                    + "яркости сохраняется: по обе стороны границы медиана берётся из «своей» части окна. "
                    + "Лучший фильтр для шума «соль-перец» до 20–25%."),
    MIN("Фильтр минимума", Group.ORDER,
            "Результат — наименьший элемент упорядоченного ряда (ранг 0). Убирает белые импульсы («соль»), "
                    + "но тёмные объекты расширяются на радиус окна. Это полутоновая эрозия."),
    MAX("Фильтр максимума", Group.ORDER,
            "Результат — наибольший элемент (ранг n − 1). Убирает чёрные импульсы («перец»), светлые объекты "
                    + "расширяются. Это полутоновая дилатация."),
    MIDPOINT("Фильтр средней точки", Group.ORDER,
            "Результат — (min + max) / 2. Объединяет порядковые статистики и усреднение. Хорош для гауссова "
                    + "и равномерного шума, но непригоден для импульсного: один импульс 0 или 255 сразу сдвигает min или max."),
    ALPHA_TRIMMED("Фильтр усечённого среднего (α-trimmed)", Group.ORDER,
            "Ряд упорядочивается, d наименьших и d наибольших значений отбрасываются, остальные усредняются: "
                    + "f = Σ g(i) / (n − 2d). При d = 0 — обычное среднее, при d = (n − 1)/2 — медиана. "
                    + "Лучший выбор для смешанного шума (гауссов + импульсный): крайние значения-импульсы отбрасываются, "
                    + "оставшиеся усредняются и подавляют гауссову составляющую."),
    PERCENTILE("Ранговый фильтр (процентиль)", Group.ORDER,
            "Общий вид всех порядковых фильтров: результат — элемент с номером k = p·(n − 1) в упорядоченном ряду. "
                    + "p = 0 — минимум, p = 50% — медиана, p = 100% — максимум. Промежуточные p — «мягкие» эрозия "
                    + "и дилатация, менее чувствительные к одиночным импульсам."),
    ADAPTIVE_MEDIAN("Адаптивный медианный фильтр", Group.ORDER,
            "Уровень A: в окне S считаются zmin, zmed, zmax. Если zmin < zmed < zmax — медиана не импульс, "
                    + "переход к B; иначе окно увеличивается, пока не достигнет Smax (тогда результат — zmed). "
                    + "Уровень B: если zmin < z < zmax — сам пиксель не импульс и остаётся без изменений, иначе "
                    + "заменяется на zmed. Справляется с плотным шумом (40–50%) и почти не трогает неповреждённые пиксели."),
    MORPHOLOGY("Морфология (min/max фильтры)", Group.ORDER,
            "Эрозия = фильтр минимума, дилатация = фильтр максимума по структурирующему элементу (форма окна). "
                    + "Открытие = дилатация(эрозия) убирает светлые детали меньше элемента, закрытие — тёмные. "
                    + "Градиент = дилатация − эрозия выделяет контуры. Top-Hat = f − открытие оставляет мелкие светлые "
                    + "детали и убирает неоднородный фон, Black-Hat = закрытие − f — мелкие тёмные детали."),
    LINEAR("Линейное сглаживание (для сравнения)", Group.LINEAR,
            "Усредняющий фильтр и фильтр Гаусса — линейные: результат — взвешенная сумма пикселей окна. "
                    + "Импульсы не удаляются, а размазываются в пятна, границы размываются. Свёртка разделяемая: "
                    + "ядро G(x, y) = g(x)·g(y), поэтому сначала проход по строкам, затем по столбцам — O(K) вместо O(K²) "
                    + "на пиксель.");

    public enum Group {
        THRESHOLD, ORDER, LINEAR
    }

    private final String title;
    private final Group group;
    private final String description;

    Method(String title, Group group, String description) {
        this.title = title;
        this.group = group;
        this.description = description;
    }

    public Group group() {
        return group;
    }

    public boolean isThreshold() {
        return group == Group.THRESHOLD;
    }

    public boolean isRankFilter() {
        return this == MEDIAN || this == MIN || this == MAX || this == MIDPOINT || this == ALPHA_TRIMMED
                || this == PERCENTILE;
    }

    public String description() {
        return description;
    }

    @Override
    public String toString() {
        return title;
    }
}
